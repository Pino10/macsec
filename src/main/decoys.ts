interface HeaderLike {
  get(name: string): string | null
}

/** Which shields a response gives away: from headers, cookies and the text of the page. */
export function detectWaf(headers: HeaderLike | Record<string, string>, body = '', cookieHeader = ''): WafBehavior[] {
  const get = (n: string): string => (typeof (headers as HeaderLike).get === 'function' ? (headers as HeaderLike).get(n) ?? '' : (headers as Record<string, string>)[n] ?? '')
  const cookies = (cookieHeader || get('set-cookie')).split(/,(?=\s*[A-Za-z0-9_.-]+=)/).map((c) => c.trim().split('=')[0])
  const text = body.slice(0, 20000)
  return WAFS.filter((w) => (w.headers ?? []).some((h) => get(h) !== '') || (w.cookies && cookies.some((c) => w.cookies!.test(c))) || (w.body && w.body.test(text)))
}

/** A block, challenge or "access denied" page: it says nothing about the site behind it. */
export function isChallengePage(status: number, body: string): boolean {
  if (status === 429 || status === 503 || status === 403 || status === 406 || status === 200) return WAFS.some((w) => w.body?.test(body.slice(0, 20000)))
  return false
}

// ---- Fake open ports

const RISKY = new Set([21, 22, 23, 25, 110, 143, 445, 1433, 1521, 2375, 3306, 3389, 5432, 5900, 6379, 9200, 11211, 27017])

export interface SpoofCheck {
  spoofed: boolean
  reason: string
}

/**
 * One address with a great many open ports, or with most of the risky service ports open at once, is
 * a shield that accepts every connection, not a server running all of that.
 */
export function spoofedPorts(ports: number[], scanned: number): SpoofCheck {
  const open = [...new Set(ports)]
  const risky = open.filter((p) => RISKY.has(p)).length
  if (open.length >= 25 || (scanned > 0 && open.length >= 12 && open.length / scanned >= 0.4)) {
    return { spoofed: true, reason: `${open.length} ports answered on one address. A real server almost never runs that many services, so a firewall or shield is probably accepting every connection.` }
  }
  if (risky >= 6) {
    return { spoofed: true, reason: `${risky} different database, remote-access and mail ports answered on one address at the same time. That mix is a typical sign of a shield answering for the server.` }
  }
  return { spoofed: false, reason: '' }
}

/** Ports that a shield in front of a website really does serve, so those stay worth checking. */
export const WEB_PORTS = new Set([80, 443, 8080, 8443])

// ---- Fake files

/** Names that firewalls and honeypots are known to answer for, and that a real site seldom has. */
export const DECOY_NAMES = [
  'trace.axd', 'elmah.axd', 'db.sql', 'dump.sql', 'database.sql', 'backup.sql', 'backup.zip', 'site.zip', 'www.zip', 'web.config',
  '.env', '.git/config', '.git/head', '.svn/entries', 'phpinfo.php', 'info.php', 'server-status', 'wp-config.php.bak', 'config.php.bak',
  'id_rsa', '.htpasswd', 'admin.zip', 'passwords.txt', 'users.sql', 'credentials.json', 'config.json'
]

function pathOf(f: Finding): string {
  return (/^(?:Public file|Exists but protected): (.+)$/.exec(f.title)?.[1] ?? '').toLowerCase()
}

/**
 * When a site answers for four or more of these names at once, it is a decoy, not four leaks.
 * The files are kept, turned down to info and explained, and one summary says so. A real leak has
 * a different content and is then still found by the secret checks on what the file holds.
 */
export function groupDecoyFiles(findings: Finding[], minimum = 4): Finding[] {
  const hits = findings.filter((f) => /^Public file: /.test(f.title) && DECOY_NAMES.some((n) => pathOf(f).endsWith(n)))
  if (hits.length < minimum) return findings
  const ids = new Set(hits.map((f) => f.id))
  const out = findings.map((f) =>
    ids.has(f.id)
      ? { ...f, severity: 'info' as const, confidence: 'possible' as const, title: `Probably a decoy: ${pathOf(f)}`, aiNote: 'Many sensitive file names answered on this site at once, which is what a firewall decoy does.' }
      : f
  )
  const host = hits[0].file ?? hits[0].url ?? ''
  out.push({
    id: `decoy-files-${host}`,
    tool: 'MacSec',
    category: 'web',
    severity: 'info',
    confidence: 'possible',
    title: `${hits.length} sensitive file names answered: probably a firewall decoy`,
    url: hits[0].url,
    file: host,
    description: `${hits.map(pathOf).slice(0, 8).join(', ')} all answered. Firewalls and honeypots do this on purpose to waste a scanner's time. They are listed as info. If you know that one of them is real, open it by hand and mark the others "Not a problem, remember".`,
    fix: 'Nothing to fix if they are decoys. If one is a real file, remove it from the web folder.'
  })
  return out
}

// ---- Keys that are not real

const PLACEHOLDER = /(x{4,}|\*{4,}|\.{4,}|your[_-]?(api|secret|key|token)|example|sample|dummy|placeholder|changeme|change[_-]me|insert[_-]|replace[_-]?me|test[_-]?key|0000000|1234567|abcdef|<[a-z_ -]+>|\$\{[^}]+\})/i

/** Example, empty or repeated values that are not real secrets. */
export function isPlaceholderKey(value: string): boolean {
  const v = value.trim()
  if (v.length < 8) return true
  if (PLACEHOLDER.test(v)) return true
  if (/^(.)\1+$/.test(v)) return true
  // Almost all one character, such as AAAAAAAAAAAA1.
  const top = Math.max(...Object.values([...v].reduce<Record<string, number>>((m, c) => ((m[c] = (m[c] ?? 0) + 1), m), {})))
  return top / v.length > 0.8
}

// ---- Public libraries and their maps

const PUBLIC_HOSTS = /(^|\.)(cdnjs\.cloudflare\.com|cdn\.jsdelivr\.net|unpkg\.com|ajax\.googleapis\.com|code\.jquery\.com|stackpath\.bootstrapcdn\.com|maxcdn\.bootstrapcdn\.com|cdn\.bootcss\.com|fonts\.googleapis\.com|www\.gstatic\.com|polyfill\.io)$/i
const PUBLIC_LIBS = /(^|[\/._-])(jquery|bootstrap|moment|lodash|underscore|angular|react|react-dom|vue|popper|axios|d3|chart|swiper|select2|datatables|fontawesome|polyfills?|vendor|runtime|webpack)([._-]|$)/i

/** A map or script that belongs to a public library, not to the site: its source is already public. */
export function isPublicLibrary(url: string): boolean {
  try {
    const u = new URL(url)
    if (PUBLIC_HOSTS.test(u.hostname)) return true
    return PUBLIC_LIBS.test(u.pathname.split('/').pop() ?? '') || /\/node_modules\//.test(u.pathname)
  } catch {
    return false
  }
}

// ---- Library versions and series

interface Series {
  /** The lowest and highest major version that really exists. */
  min: number
  max: number
  /** Notes by major version. */
  notes: Record<number, string>
}

export const SERIES: Record<string, Series> = {
  Bootstrap: { min: 1, max: 5, notes: { 2: 'Bootstrap 2 is long out of support.', 3: 'Bootstrap 3 has not had fixes since 2019.', 4: 'Bootstrap 4 stopped getting fixes in January 2023.' } },
  jQuery: { min: 1, max: 4, notes: { 1: 'jQuery 1.x is out of support.', 2: 'jQuery 2.x is out of support.' } },
  'Moment.js': { min: 1, max: 2, notes: { 2: 'Moment.js is in maintenance only: its authors suggest a newer date library.' } },
  AngularJS: { min: 1, max: 1, notes: { 1: 'AngularJS (version 1) stopped getting fixes in December 2021.' } },
  'Vue.js': { min: 0, max: 3, notes: { 0: 'Vue 0.x and 1.x are out of support.', 1: 'Vue 0.x and 1.x are out of support.', 2: 'Vue 2 stopped getting fixes at the end of 2023.' } }
}

/** Does this version fit a series that exists? A made-up or misread number is not checked against flaws. */
export function plausibleVersion(name: string, version: string): boolean {
  const s = SERIES[name]
  const major = Number(version.split('.')[0])
  if (!Number.isFinite(major)) return false
  if (!s) return true
  return major >= s.min && major <= s.max
}

/** "Bootstrap 4.x": the series, and what is known about it. */
export function seriesNote(name: string, version: string): string {
  const major = Number(version.split('.')[0])
  const s = SERIES[name]
  if (!s || !Number.isFinite(major)) return ''
  return `Series: ${name} ${major}.x. ${s.notes[major] ?? 'This series is still maintained.'}`
}

// ---- Showing what was seen

/** The line a key was found on, with every long value cut to its first four characters. */
export function seenLine(line: string): string {
  const cut = line.length > 220 ? line.slice(0, 220) + '…' : line
  return cut.replace(/(["'`=:\s])([A-Za-z0-9_\-+/=.]{12,})(?=["'`,;\s)]|$)/g, (_m, a: string, v: string) => `${a}${v.slice(0, 4)}…(${v.length} characters)`)
}

/** The quoted values on a line that could be a key. Used to tell an example from a real one. */
export function valuesOnLine(line: string): string[] {
  return [...line.matchAll(/["'`]([^"'`\s]{8,})["'`]/g)].map((m) => m[1])
}

/**
 * Gives a key finding the line it was found on, and turns it down when every value on that line is an
 * example. The value itself is never kept: only its first four characters and its length.
 */
export function explainKey(f: Finding, line: string | undefined): Finding {
  if (!line) return f
  const out: Finding = { ...f, description: `${f.description ?? ''} What MacSec saw: ${seenLine(line.trim())}`.trim() }
  const values = valuesOnLine(line)
  if (values.length && values.every(isPlaceholderKey)) {
    return { ...out, severity: 'info', confidence: 'possible', title: `${f.title.replace(/ in public JavaScript$/, '')}: looks like an example value`, aiNote: 'Every value on that line looks like a placeholder, not a real key.' }
  }
  return out
}
